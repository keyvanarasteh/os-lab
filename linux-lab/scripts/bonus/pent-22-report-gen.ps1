# PENT-22: AI-Use Disclosure & Analysis Report Generator
param (
    [Parameter(Mandatory=$true)][string]$LogFile,
    [Parameter(Mandatory=$true)][string]$OutFile
)

if (-Not (Test-Path $LogFile)) {
    Write-Error "[hata] Log dosyasi '$LogFile' bulunamadi."
    exit 1
}

$logContent = Get-Content $LogFile -Raw

# Kapsam Kontrolü (Sadece Lab IP'lerine izin ver)
$ipRegex = "((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)"
if ($logContent -match $ipRegex) {
    $allowedRegex = "(127\.|10\.|172\.(1[6-9]|2[0-9]|3[0-1])\.|192\.168\.)"
    if ($logContent -notmatch $allowedRegex) {
        Write-Error "[hata] Kapsam disi (out-of-scope) hedef tespit edildi. Islem durduruldu."
        exit 1
    }
}

Write-Host "Rapor $OutFile konumuna olusturuluyor..."

$date = (Get-Date).ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss UTC")
$commands = (Get-Content $LogFile | Where-Object { $_ -match "^(exec|run|cmd|#)" }) -join "`n"
if (-Not $commands) { $commands = "No explicit commands found." }

$reportContent = @"
# Penetration Testing Analysis Report

**Date:** $date
**Status:** Completed
**Scope:** Verified Isolated Lab Environment

## 1. Executive Summary
This report was automatically generated from the session log \`$LogFile\`. The analysis focused on identifying and mitigating vulnerabilities within the authorized lab boundaries.

## 2. Reproducibility Steps
The following key actions were extracted from the session log to ensure full reproducibility:

\`\`\`text
$commands
\`\`\`

## 3. Full Session Log
\`\`\`text
$logContent
\`\`\`

## 4. AI-Use Disclosure Appendix
* **AI Assistance:** Yes
* **Models Used:** Gemini
* **Purpose:** Formatting this report, structuring the generator script, and verifying syntax for compliance. All commands were manually executed and verified by the authorized user.

---
*Report generated by PENT-22.*
"@

Set-Content -Path $OutFile -Value $reportContent -Encoding UTF8
Write-Host "[tamam] Rapor basariyla uretildi: $OutFile" -ForegroundColor Green
